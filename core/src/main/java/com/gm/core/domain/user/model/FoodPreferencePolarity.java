package com.gm.core.domain.user.model;

/**
 * 음식 취향 추출의 극성. 어느 입력칸에서 온 요청인지를 AI 추출까지 전달한다.
 *
 * <p>극성을 넘기지 않으면 "면요리는 싫고 국물은 좋아요"처럼 한 문장에 양극성이 섞였을 때
 * 두 키워드가 모두 한쪽으로 저장된다. 호출한 입력칸의 극성에 해당하는 키워드만 뽑도록
 * 프롬프트를 분기하기 위한 값이다.</p>
 */
public enum FoodPreferencePolarity {

    /** 좋아한다고 말한 음식만 추출한다. */
    LIKE,

    /** 싫다·못 먹는다고 말한 음식만 추출한다. */
    EXCLUDE
}
